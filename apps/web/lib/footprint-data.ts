export const FOOTPRINT_CENTER: [number, number] = [-73.9851, 40.7589];

function offset(c: [number, number], dx: number, dy: number): [number, number] {
  return [c[0] + dx, c[1] + dy];
}

function wobble(
  c: [number, number],
  spans: Array<[number, number]>,
): Array<[number, number]> {
  const path: Array<[number, number]> = [c];
  for (const [dx, dy] of spans) {
    const last = path[path.length - 1];
    path.push(offset(last, dx, dy));
  }
  return path;
}

